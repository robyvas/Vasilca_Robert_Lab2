using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.RazorPages;
using Microsoft.EntityFrameworkCore;
using Vasilca_Robert_Lab2.Models;

namespace Vasilca_Robert_Lab2.Pages.Borrowings
{
    public class DetailsModel : PageModel
    {
        private readonly Vasilca_Robert_Lab2Context _context;

        public DetailsModel(Vasilca_Robert_Lab2Context context)
        {
            _context = context;
        }

        public Borrowing Borrowing { get; set; } = default!;

        public async Task<IActionResult> OnGetAsync(int? id)
        {
            if (id == null)
            {
                return NotFound();
            }

            var borrowing = await _context.Borrowing
                .Include(b => b.Member)
                .Include(b => b.Book)
                .ThenInclude(b => b.Author)
                .FirstOrDefaultAsync(m => m.ID == id);

            if (borrowing is not null)
            {
                Borrowing = borrowing;

                return Page();
            }

            return NotFound();
        }
    }
}
